import { existsSync, readFileSync } from 'node:fs';
import { defineConfig, postcssIsolateStyles, type DefaultTheme } from 'vitepress';
import { withMermaid } from 'vitepress-plugin-mermaid';

// DOCS_BASE (path, e.g. /actorium/) and DOCS_URL (full site URL, for the
// sitemap) come from actions/configure-pages in CI, so a project page, user
// page or custom domain needs no code change. Locally: base `/`, no sitemap.
const segment = (process.env.DOCS_BASE ?? '').replace(/^\/+|\/+$/g, '');
const base = segment ? `/${segment}/` : '/';
// configure-pages reports the URL without a trailing slash; the sitemap
// resolves page paths against it, so it must end in one to keep the path.
const hostname = process.env.DOCS_URL?.replace(/\/*$/, '/');
const { version } = JSON.parse(
  readFileSync(new URL('../../packages/xstate-otel/package.json', import.meta.url), 'utf8'),
) as { version: string };

// Generated by TypeDoc (`docs:api`) before every dev or build run.
const apiSidebarFile = new URL('../xstate-otel/api/typedoc-sidebar.json', import.meta.url);
const apiSidebar: DefaultTheme.SidebarItem[] = existsSync(apiSidebarFile)
  ? JSON.parse(readFileSync(apiSidebarFile, 'utf8'))
  : [];

const sidebar: DefaultTheme.SidebarItem[] = [
  {
    text: 'Guide',
    items: [
      { text: 'Introduction', link: '/xstate-otel/guide/introduction' },
      { text: 'Getting started', link: '/xstate-otel/guide/getting-started' },
      { text: 'Commands', link: '/xstate-otel/guide/commands' },
      { text: 'Promise work', link: '/xstate-otel/guide/promise-work' },
      { text: 'Actor messages and actions', link: '/xstate-otel/guide/actor-messages' },
      { text: 'Timers', link: '/xstate-otel/guide/scheduled-work' },
      { text: 'Showcase', link: '/xstate-otel/guide/showcase' },
    ],
  },
  {
    text: 'Recipes',
    items: [
      { text: 'HTTP and message boundaries', link: '/xstate-otel/recipes/http-boundaries' },
      { text: 'Frameworks', link: '/xstate-otel/recipes/frameworks' },
      { text: 'Testing with waitForBookkeeping()', link: '/xstate-otel/recipes/testing' },
    ],
  },
  {
    text: 'Reference',
    items: [
      { text: 'Configuration', link: '/xstate-otel/reference/configuration' },
      { text: 'Outcomes and errors', link: '/xstate-otel/reference/outcomes' },
      { text: 'Attributes', link: '/xstate-otel/reference/attributes' },
      { text: 'Compatibility', link: '/xstate-otel/reference/compatibility' },
      { text: 'Glossary', link: '/xstate-otel/reference/glossary' },
      { text: 'API', collapsed: true, items: apiSidebar },
    ],
  },
  {
    text: 'Explanation',
    items: [
      { text: 'Model and operation lifecycle', link: '/xstate-otel/explanation/model' },
      { text: 'Inspection and ordering', link: '/xstate-otel/explanation/inspection-and-ordering' },
      { text: 'Scheduler internals', link: '/xstate-otel/explanation/scheduler' },
      { text: 'Performance', link: '/xstate-otel/explanation/performance' },
      { text: 'Edge cases', link: '/xstate-otel/explanation/edge-cases' },
    ],
  },
];

const config = withMermaid(
  defineConfig({
    title: 'Actorium',
    description: 'Tools for XState actor systems',
    base,
    cleanUrls: true,
    srcExclude: ['snippets/**'],
    transformHead({ pageData }) {
      return pageData.relativePath === 'index.md'
        ? [['meta', { 'http-equiv': 'refresh', content: `0;url=${base}xstate-otel/` }]]
        : [];
    },
    // Mermaid is one large client chunk; the warning is expected.
    vite: {
      build: { chunkSizeWarningLimit: 4000 },
      css: {
        postcss: {
          // Keep viewer typography isolated while allowing VitePress link navigation.
          plugins: [
            postcssIsolateStyles({
              prefix: ':not(:where(.vp-raw, .vp-raw *, .showcase-viewer, .showcase-viewer *))',
              includeFiles: [/base\.css$/, /vp-doc\.css$/],
            }),
          ],
        },
      },
    },
    ...(hostname ? { sitemap: { hostname } } : {}),
    themeConfig: {
      nav: [
        {
          text: `xstate-otel v${version}`,
          activeMatch: '^/xstate-otel/',
          items: [
            { text: 'Overview', link: '/xstate-otel/' },
            { text: 'Guide', link: '/xstate-otel/guide/introduction' },
            { text: 'Reference', link: '/xstate-otel/reference/configuration' },
            { text: 'API', link: '/xstate-otel/api/' },
          ],
        },
      ],
      sidebar: {
        '/xstate-otel/': [
          {
            text: `xstate-otel v${version}`,
            link: '/xstate-otel/',
            collapsed: false,
            items: sidebar,
          },
        ],
      },
      search: { provider: 'local' },
      socialLinks: [{ icon: 'github', link: 'https://github.com/c0m1t/actorium' }],
    },
  }),
);

// Prebundle Mermaid itself so pnpm resolves all its CommonJS dependencies.
const dependencies = config.vite?.optimizeDeps;
if (dependencies) dependencies.include = ['mermaid'];

export default config;
